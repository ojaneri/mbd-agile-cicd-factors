"""Generate the MIL model (Modelica) and the production C code from one spec (single source of truth).

Usage: python gen.py <spec.json> <out_dir>
Writes FuelFlow.mo, fuel.h, fuel.c, fuel_expect.h (unit-test expectations derived from the spec).
Lessons from subject 1 applied: no identifier shared between model variables and function arguments;
outputs assigned inside the when-statement (OpenModelica 1.27.2 dropped algorithm assignments to a
variable alias-eliminated against an output); C float literals always carry a decimal point.
"""
import json
import pathlib
import sys

import ref


def f32(x):
    s = f"{float(x):.9g}"
    if not any(c in s for c in ".e"):
        s += ".0"
    return s + "f"


def modelica(spec):
    p, e = spec["params"], spec["eq"]
    trim = ("      if trimS > trimLim then trimS := trimLim; end if;\n"
            "      if trimS < -trimLim then trimS := -trimLim; end if;\n") if e["trim_clamp"] else ""
    dfco = "      if thr <= thrDfco and rpm > rpmDfco then rateS := 0.0; end if;\n" if e["dfco"] else ""
    sat = ("      if rateS > rateMax then rateS := rateMax; end if;\n"
           "      if rateS < 0.0 then rateS := 0.0; end if;\n") if e["sat"] else ""
    return f"""// Generated by gen.py from spec version '{spec['version']}'. Do not edit.
model FuelFlow
  parameter Real kCal = {p['k_cal']!r};
  parameter Real afr = {p['AFR']!r};
  parameter Real rhoF = {p['rho']!r};
  parameter Real dtMax = {p['dt_max']!r};
  parameter Real trimLim = {p['trim_lim']!r};
  parameter Real rateMax = {p['rate_max']!r};
  parameter Real thrDfco = {p['thr_dfco']!r};
  parameter Real rpmDfco = {p['rpm_dfco']!r};
  parameter Real dtScale = {e['dt_scale']!r};
  input Real dtIn;
  input Real maf;
  input Real rpm;
  input Real thr;
  input Real stft;
  input Real ltft;
  output Real rate(start = 0.0, fixed = true);
  output Real vol(start = 0.0, fixed = true);
protected
  discrete Real volS(start = 0.0, fixed = true);
  discrete Real rateS(start = 0.0, fixed = true);
  discrete Real trimS(start = 0.0, fixed = true);
  discrete Real dtc(start = 0.0, fixed = true);
algorithm
  // One data row per unit of model time: the sample at j+0.5 processes row j (inputs held over [j, j+1)).
  when sample(0.5, 1.0) then
      trimS := stft + ltft;
{trim}      rateS := kCal * maf * 60.0 / (afr * rhoF) * (1.0 + ({float(e['s_trim']):.1f}) * trimS / 100.0);
{dfco}{sat}      dtc := dtIn;
      if dtc > dtMax then dtc := dtMax; end if;
      if dtc < 0.0 then dtc := 0.0; end if;
      volS := volS + ({float(e['s_int']):.1f}) * rateS * dtc * dtScale / 60.0;
      rate := rateS;
      vol := volS;
  end when;
end FuelFlow;
"""


HEADER = """/* Generated by gen.py. Do not edit. */
#ifndef FUEL_H
#define FUEL_H
typedef struct {
    float vol;
    float rate;
} fuel_t;
void fuel_init(fuel_t *f);
float fuel_rate_of(float maf, float rpm, float thr, float stft, float ltft);
float fuel_step(fuel_t *f, float dt, float maf, float rpm, float thr, float stft, float ltft);
#endif
"""


def c_source(spec):
    p, e = spec["params"], spec["eq"]
    trim = ("    if (trim > TRIM_LIM) {\n        trim = TRIM_LIM;\n    }\n"
            "    if (trim < -TRIM_LIM) {\n        trim = -TRIM_LIM;\n    }\n") if e["trim_clamp"] else ""
    dfco = ("    if (thr <= THR_DFCO && rpm > RPM_DFCO) {\n        rate = 0.0f;\n    }\n") if e["dfco"] else ""
    sat = ("    if (rate > RATE_MAX) {\n        rate = RATE_MAX;\n    }\n"
           "    if (rate < 0.0f) {\n        rate = 0.0f;\n    }\n") if e["sat"] else ""
    return f"""/* Generated by gen.py from spec version '{spec['version']}'. Do not edit. */
#include "fuel.h"

#define K_CAL {f32(p['k_cal'])}
#define AFR {f32(p['AFR'])}
#define RHO {f32(p['rho'])}
#define DT_MAX {f32(p['dt_max'])}
#define TRIM_LIM {f32(p['trim_lim'])}
#define RATE_MAX {f32(p['rate_max'])}
#define THR_DFCO {f32(p['thr_dfco'])}
#define RPM_DFCO {f32(p['rpm_dfco'])}
#define DT_SCALE {f32(e['dt_scale'])}

void fuel_init(fuel_t *f)
{{
    f->vol = 0.0f;
    f->rate = 0.0f;
}}

float fuel_rate_of(float maf, float rpm, float thr, float stft, float ltft)
{{
    float trim = stft + ltft;
{trim}    float rate = K_CAL * maf * 60.0f / (AFR * RHO) * (1.0f + ({float(e['s_trim']):.1f}f) * trim / 100.0f);
{dfco}{sat}    return rate;
}}

float fuel_step(fuel_t *f, float dt, float maf, float rpm, float thr, float stft, float ltft)
{{
    float rate = fuel_rate_of(maf, rpm, thr, stft, ltft);
    float dtc = dt;
    if (dtc > DT_MAX) {{
        dtc = DT_MAX;
    }}
    if (dtc < 0.0f) {{
        dtc = 0.0f;
    }}
    f->vol = f->vol + ({float(e['s_int']):.1f}f) * rate * dtc * DT_SCALE / 60.0f;
    f->rate = rate;
    return f->vol;
}}
"""


def expect_header(spec):
    """Unit expectations from the spec with the float64 reference (design intent)."""
    pts = []
    for maf in (0.0, 2.0, 10.0, 35.0, 120.0, -3.0):
        for rpm, thr in ((750.0, 19.0), (2500.0, 30.0), (2500.0, 20.0), (1200.0, 20.0)):
            for st, lt in ((0.0, 0.0), (5.0, -2.0), (40.0, 30.0), (-40.0, -10.0)):
                pts.append((maf, rpm, thr, st, lt))
    rates = [ref.step(spec, 0.0, 1.0, *q)[1] for q in pts]
    steps = []
    for dt in (1.0, 0.25, 4.9, 30.0, -1.0, 0.0):
        for q in ((10.0, 2500.0, 30.0, 2.0, 1.0), (2.0, 750.0, 19.0, 0.0, 0.0)):
            v, _ = ref.step(spec, 100.0, dt, *q)
            steps.append((dt,) + q + (v,))
    fmt = lambda rows: ",\n    ".join("{" + ", ".join(repr(float(x)) for x in r) + "}" for r in rows)
    return ("/* Generated by gen.py: unit-test expectations from the spec. Do not edit. */\n"
            f"#define UT_N_RATE {len(pts)}\n"
            f"static const double UT_RATE_IN[UT_N_RATE][5] = {{\n    {fmt(pts)}\n}};\n"
            f"static const double UT_RATE_EXP[UT_N_RATE] = {{{', '.join(repr(float(r)) for r in rates)}}};\n"
            f"#define UT_N_STEP {len(steps)}\n"
            "/* dt, maf, rpm, thr, stft, ltft, expected volume after one step from 100 ml */\n"
            f"static const double UT_STEP[UT_N_STEP][7] = {{\n    {fmt(steps)}\n}};\n")


def generate(spec, out):
    out = pathlib.Path(out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "FuelFlow.mo").write_text(modelica(spec))
    (out / "fuel.h").write_text(HEADER)
    (out / "fuel.c").write_text(c_source(spec))
    (out / "fuel_expect.h").write_text(expect_header(spec))
    (out / "spec.json").write_text(json.dumps(spec, indent=1))


if __name__ == "__main__":
    generate(json.loads(pathlib.Path(sys.argv[1]).read_text()), sys.argv[2])
