"""Generate the MIL model (Modelica) and the production C code of subject 3 from one spec.

Usage: python gen.py <spec.json> <out_dir>
Writes BessTherm.mo, bess.h, bess.c, bess_expect.h (unit-test expectations derived from the spec).
Lessons from subjects 1-2 applied: no identifier shared between model variables and inputs; outputs
assigned inside the when-statement (OpenModelica 1.27.2 dropped algorithm assignments to a variable
alias-eliminated against an output); C float literals always carry a decimal point; one C statement per
line with braces on their own lines (so the code-level operators see every site); locals declared first
and assigned later (so a deleted assignment leaves an uninitialised local, a defect class E5 studies).
"""
import json
import pathlib
import sys

import ref


def f32(x):
    s = f"{float(x):.9g}"
    if not any(c in s for c in ".e"):
        s += ".0"
    return s + "f"


def _release_mo(e):
    lo = "tLo" if e["hyst"] else "tHi"
    return {"both": f"tfS < {lo} and dwS >= dwellS", "temp": f"tfS < {lo}", "dwell": "dwS >= dwellS"}[e["rel_rule"]]


def modelica(spec):
    p, e = spec["params"], spec["eq"]
    icl = ("      if ic > iMax then ic := iMax; end if;\n"
           "      if ic < -iMax then ic := -iMax; end if;\n") if e["iclamp"] else ""
    sat = ("      if teS > tMax then teS := tMax; end if;\n"
           "      if teS < tMin then teS := tMin; end if;\n") if e["sat"] else ""
    ramp = ("      if tgt < derS then\n        derS := tgt;\n      else\n        derS := derS + rampS * dtS;\n"
            "        if derS > tgt then derS := tgt; end if;\n      end if;\n") if e["ramp"] else "      derS := tgt;\n"
    return f"""// Generated by gen.py from spec version '{spec['version']}'. Do not edit.
model BessTherm
  parameter Real dtS = {ref.DT!r};
  parameter Real tauT = {p['tau']!r};
  parameter Real kH = {p['k_h']!r};
  parameter Real c0 = {p['c0']!r};
  parameter Integer nSub = {int(p['n_sub'])};
  parameter Real iMax = {p['i_max']!r};
  parameter Real tMin = {p['t_min']!r};
  parameter Real tMax = {p['t_max']!r};
  parameter Real tauF = {p['tau_f']!r};
  parameter Real tHi = {p['t_hi']!r};
  parameter Real tLo = {p['t_lo']!r};
  parameter Real dwellS = {p['dwell_s']!r};
  parameter Real dLim = {p['d_lim']!r};
  parameter Real rampS = {p['ramp']!r};
  parameter Real dtScale = {e['dt_scale']!r};
  input Real rst;
  input Real cur;
  input Real tref;
  output Real tEst(start = 0.0, fixed = true);
  output Real derate(start = 1.0, fixed = true);
protected
  discrete Real teS(start = 0.0, fixed = true);
  discrete Real tfS(start = 0.0, fixed = true);
  discrete Real dwS(start = 0.0, fixed = true);
  discrete Real derS(start = 1.0, fixed = true);
  discrete Boolean latchS(start = false, fixed = true);
  discrete Real ic(start = 0.0, fixed = true);
  discrete Real hS(start = 0.0, fixed = true);
  discrete Real tgt(start = 1.0, fixed = true);
algorithm
  // One data row per unit of model time: the sample at j+0.5 processes row j (inputs held over [j, j+1)).
  when sample(0.5, 1.0) then
      if rst > 0.5 then
        teS := tref + ({float(e['s_c0']):.1f}) * c0;
        tfS := teS;
        latchS := false;
        dwS := 0.0;
        derS := 1.0;
      end if;
      ic := cur;
{icl}      hS := dtS * dtScale / nSub;
      for k in 1:nSub loop
        teS := teS + hS / tauT * (tref + ({float(e['s_c0']):.1f}) * c0 + ({float(e['s_heat']):.1f}) * kH * ic * ic - teS);
      end for;
{sat}      tfS := tfS + dtS / (tauF + dtS) * (teS - tfS);
      if not latchS then
        if tfS > tHi then
          latchS := true;
          dwS := 0.0;
        end if;
      else
        dwS := dwS + dtS;
        if {_release_mo(e)} then
          latchS := false;
        end if;
      end if;
      if latchS then
        tgt := dLim;
      else
        tgt := 1.0;
      end if;
{ramp}      tEst := teS;
      derate := derS;
  end when;
end BessTherm;
"""


HEADER = """/* Generated by gen.py. Do not edit. */
#ifndef BESS_H
#define BESS_H
#include <stdint.h>
typedef struct {
    float t_est;
    float t_filt;
    float der;
    int latch;
    uint32_t dwell_ms;
} bess_t;
void bess_init(bess_t *o, float tref);
float bess_therm(float te0, float cur, float tref);
void bess_derate(bess_t *o, float te);
float bess_step(bess_t *o, float cur, float tref);
#endif
"""


def _release_c(e):
    lo = "T_LO" if e["hyst"] else "T_HI"
    return {"both": f"o->t_filt < {lo} && o->dwell_ms >= DWELL_MS", "temp": f"o->t_filt < {lo}",
            "dwell": "o->dwell_ms >= DWELL_MS"}[e["rel_rule"]]


def c_source(spec):
    p, e = spec["params"], spec["eq"]
    icl = ("    if (ic > I_MAX) {\n        ic = I_MAX;\n    }\n"
           "    if (ic < -I_MAX) {\n        ic = -I_MAX;\n    }\n") if e["iclamp"] else ""
    sat = ("    if (acc > T_MAX) {\n        acc = T_MAX;\n    }\n"
           "    if (acc < T_MIN) {\n        acc = T_MIN;\n    }\n") if e["sat"] else ""
    ramp = ("    if (tgt < o->der) {\n        o->der = tgt;\n    } else {\n        o->der = o->der + RAMP_STEP;\n"
            "        if (o->der > tgt) {\n            o->der = tgt;\n        }\n    }\n") if e["ramp"] else "    o->der = tgt;\n"
    h = ref.DT * e["dt_scale"] / p["n_sub"]
    return f"""/* Generated by gen.py from spec version '{spec['version']}'. Do not edit. */
#include "bess.h"

#define TAU {f32(p['tau'])}
#define K_H {f32(p['k_h'])}
#define C0 {f32(p['c0'])}
#define N_SUB {int(p['n_sub'])}
#define H_SUB {f32(h)}
#define I_MAX {f32(p['i_max'])}
#define T_MIN {f32(p['t_min'])}
#define T_MAX {f32(p['t_max'])}
#define ALPHA {f32(ref.DT / (p['tau_f'] + ref.DT))}
#define T_HI {f32(p['t_hi'])}
#define T_LO {f32(p['t_lo'])}
#define DT_MS {int(round(ref.DT * 1000))}u
#define DWELL_MS {int(round(p['dwell_s'] * 1000))}u
#define D_LIM {f32(p['d_lim'])}
#define RAMP_STEP {f32(p['ramp'] * ref.DT)}

void bess_init(bess_t *o, float tref)
{{
    o->t_est = tref + ({float(e['s_c0']):.1f}f) * C0;
    o->t_filt = o->t_est;
    o->der = 1.0f;
    o->latch = 0;
    o->dwell_ms = 0u;
}}

float bess_therm(float te0, float cur, float tref)
{{
    float ic;
    float acc;
    ic = cur;
{icl}    acc = te0;
    for (int k = 0; k < N_SUB; k++) {{
        acc = acc + H_SUB / TAU * (tref + ({float(e['s_c0']):.1f}f) * C0 + ({float(e['s_heat']):.1f}f) * K_H * ic * ic - acc);
    }}
{sat}    return acc;
}}

void bess_derate(bess_t *o, float te)
{{
    float tgt;
    o->t_filt = o->t_filt + ALPHA * (te - o->t_filt);
    if (o->latch == 0) {{
        if (o->t_filt > T_HI) {{
            o->latch = 1;
            o->dwell_ms = 0u;
        }}
    }} else {{
        o->dwell_ms = o->dwell_ms + DT_MS;
        if ({_release_c(e)}) {{
            o->latch = 0;
        }}
    }}
    tgt = 1.0f;
    if (o->latch != 0) {{
        tgt = D_LIM;
    }}
{ramp}}}

float bess_step(bess_t *o, float cur, float tref)
{{
    float te;
    te = bess_therm(o->t_est, cur, tref);
    o->t_est = te;
    bess_derate(o, te);
    return te;
}}
"""


def expect_header(spec):
    """Unit expectations from the spec with the float64 reference (design intent)."""
    th = []
    for te0 in (20.0, 26.0, 31.5, 85.0):
        for cur in (0.0, 60.0, -120.0, 170.0, 1000.0):
            for tref in (22.0, 28.0, 33.0):
                th.append((te0, cur, tref, ref.therm(spec, te0, cur, tref)))
    dr = []
    # (t_filt, latch, dwell_s, der, te) -> (t_filt', latch', dwell_ms', der')
    for tf, lat, dw, der in ((30.9, 0, 0.0, 1.0), (31.2, 0, 0.0, 1.0), (30.0, 1, 100.0, 0.5),
                             (28.0, 1, 295.0, 0.5), (28.0, 1, 400.0, 0.5), (25.0, 0, 0.0, 0.5),
                             (25.0, 0, 0.0, 0.995), (29.5, 1, 1000.0, 0.5)):
        for te in (24.0, 30.0, 40.0):
            s = dict(te=te, tf=tf, latch=bool(lat), dwell=dw, der=der)
            ref.derate(spec, s, te)
            dr.append((tf, lat, dw * 1000.0, der, te, s["tf"], int(s["latch"]), s["dwell"] * 1000.0, s["der"]))
    s0 = ref.init(spec, 25.0)
    fmt = lambda rows: ",\n    ".join("{" + ", ".join(repr(float(x)) for x in r) + "}" for r in rows)
    return ("/* Generated by gen.py: unit-test expectations from the spec. Do not edit. */\n"
            f"#define UT_N_TH {len(th)}\n"
            "/* te0, cur, tref, expected te after one row */\n"
            f"static const double UT_TH[UT_N_TH][4] = {{\n    {fmt(th)}\n}};\n"
            f"#define UT_N_DR {len(dr)}\n"
            "/* t_filt, latch, dwell_ms, der, te -> t_filt', latch', dwell_ms', der' */\n"
            f"static const double UT_DR[UT_N_DR][9] = {{\n    {fmt(dr)}\n}};\n"
            f"#define UT_INIT_T {s0['te']!r}\n")


def generate(spec, out):
    out = pathlib.Path(out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "BessTherm.mo").write_text(modelica(spec))
    (out / "bess.h").write_text(HEADER)
    (out / "bess.c").write_text(c_source(spec))
    (out / "bess_expect.h").write_text(expect_header(spec))
    (out / "spec.json").write_text(json.dumps(spec, indent=1))


if __name__ == "__main__":
    generate(json.loads(pathlib.Path(sys.argv[1]).read_text()), sys.argv[2])
