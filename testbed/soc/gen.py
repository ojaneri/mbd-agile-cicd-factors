"""Generate the MIL model (Modelica) and the production C code from one spec (single source of truth).

Usage: python gen.py <spec.json> <out_dir>
Writes: SocObs.mo, soc_obs.h, soc_obs.c, soc_obs_expect.h (unit-test expectations derived from the spec).
Model-level mutants are spec changes and therefore reach both the model and the code, as in a
model-to-code flow. Code-level mutants are edits of the generated soc_obs.c only (see mutate.py).
"""
import json
import pathlib
import sys

import ref


def f32(x):
    s = f"{float(x):.9g}"
    if not any(c in s for c in ".e"):
        s += ".0"
    return s + "f"


def sgn(x):
    return f"({float(x):.1f})"


def modelica(spec):
    p, e, k = spec["params"], spec["eq"], spec["params"]["knots"]
    sat = ("      if socS > 1.0 then socS := 1.0; end if;\n      if socS < 0.0 then socS := 0.0; end if;\n"
           if e["sat"] else "")
    return f"""// Generated by gen.py from spec version '{spec['version']}'. Do not edit.
model SocObs
  function ocvLookup
    input Real sx;
    input Real k[:];
    output Real v;
  protected
    Integer n = size(k, 1);
    Real x;
    Integer idx;
    Real frac;
  algorithm
    x := sx * (n - 1);
    idx := integer(x);
    if idx < 0 then idx := 0; end if;
    if idx > n - 2 then idx := n - 2; end if;
    frac := x - idx;
    v := k[idx + 1] + (k[idx + 2] - k[idx + 1]) * frac;
  end ocvLookup;

  function ocvInv
    input Real vx;
    input Real k[:];
    output Real sOut;
  protected
    Real lo = 0.0;
    Real hi = 1.0;
    Real mid;
  algorithm
    for it in 1:30 loop
      mid := 0.5 * (lo + hi);
      if ocvLookup(mid, k) < vx then lo := mid; else hi := mid; end if;
    end for;
    sOut := 0.5 * (lo + hi);
  end ocvInv;

  parameter Real dt = {p['dt']!r};
  parameter Real Q = {p['Q']!r};
  parameter Real R0 = {p['R0']!r};
  parameter Real R1 = {p['R1']!r};
  parameter Real tau = {p['tau']!r};
  parameter Real L = {p['L']!r};
  parameter Real Lrest = {p['L_rest']!r};
  parameter Real restI = {p['rest_i']!r};
  parameter Integer restMs = {int(p['rest_ms'])};
  parameter Integer dtMs = {int(round(p['dt'] * 1000))};
  parameter Real dtInt = {e['dt_int']!r};
  parameter Real k[{len(k)}] = {{{', '.join(repr(float(v)) for v in k)}}};
  parameter Real socOverride = -1.0;
  input Real I;
  input Real V;
  output Real soc(start = 0.0, fixed = true);
protected
  discrete Real socS(start = 0.0, fixed = true);
  discrete Real v1(start = 0.0, fixed = true);
  discrete Real a(start = 0.0, fixed = true);
  discrete Real iD(start = 0.0, fixed = true);
  discrete Real vm(start = 0.0, fixed = true);
  discrete Real gain(start = 0.0, fixed = true);
  discrete Integer restT(start = 0, fixed = true);
  discrete Boolean initd(start = false, fixed = true);
algorithm
  // Inputs are held over [j, j+1); the sample at j+0.5 processes data row j.
  when sample(0.5, dt) then
    if not initd then
      socS := if socOverride >= 0.0 then socOverride else ocvInv(V, k);
      v1 := 0.0;
      restT := 0;
      a := exp(-dt / tau);
      initd := true;
    else
      iD := {sgn(e['s_id'])} * I;
      v1 := a * v1 + R1 * (1.0 - a) * iD;
      socS := socS + {sgn(e['s_cc'])} * iD * dtInt / (3600.0 * Q);
      restT := if abs(I) < restI then restT + dtMs else 0;
      gain := if restT >= restMs then Lrest else L;
      vm := ocvLookup(socS, k) + {sgn(e['s_r0'])} * R0 * iD + {sgn(e['s_v1'])} * v1;
      socS := socS + {sgn(e['s_corr'])} * gain * (V - vm);
{sat}    end if;
    // Output assigned inside the when-statement: with an equation 'soc = socS', OpenModelica 1.27.2
    // alias-eliminated socS and dropped the algorithm's assignments (found 2026-11-11, output stuck at 0).
    soc := socS;
  end when;
end SocObs;
"""


HEADER = """/* Generated by gen.py. Do not edit. */
#ifndef SOC_OBS_H
#define SOC_OBS_H
#include <stdint.h>
#define SOC_OBS_N_KNOTS {n}
typedef struct {{
    float soc;
    float v1;
    float a;
    uint32_t rest_ms;
}} soc_obs_t;
extern const float SOC_OBS_KNOTS[SOC_OBS_N_KNOTS];
float soc_obs_ocv(float s);
float soc_obs_ocv_inv(float v);
void soc_obs_init(soc_obs_t *o, float v0, float soc_override);
float soc_obs_step(soc_obs_t *o, float i_meas, float v_meas);
#endif
"""


def c_source(spec):
    p, e, k = spec["params"], spec["eq"], spec["params"]["knots"]
    sat = ("    if (o->soc > 1.0f) {\n        o->soc = 1.0f;\n    }\n"
           "    if (o->soc < 0.0f) {\n        o->soc = 0.0f;\n    }\n") if e["sat"] else ""
    knots = ",\n    ".join(f32(v) for v in k)
    return f"""/* Generated by gen.py from spec version '{spec['version']}'. Do not edit. */
#include "soc_obs.h"
#include <math.h>

#define DT_S {f32(p['dt'])}
#define DT_MS {int(round(p['dt'] * 1000))}u
#define DT_INT_S {f32(e['dt_int'])}
#define Q_AH {f32(p['Q'])}
#define R0_OHM {f32(p['R0'])}
#define R1_OHM {f32(p['R1'])}
#define TAU_S {f32(p['tau'])}
#define L_GAIN {f32(p['L'])}
#define L_REST {f32(p['L_rest'])}
#define REST_I_A {f32(p['rest_i'])}
#define REST_MS {int(p['rest_ms'])}u

const float SOC_OBS_KNOTS[SOC_OBS_N_KNOTS] = {{
    {knots}
}};

float soc_obs_ocv(float s)
{{
    float x = s * (float)(SOC_OBS_N_KNOTS - 1);
    int idx = (int)x;
    if (idx < 0) {{
        idx = 0;
    }}
    if (idx > SOC_OBS_N_KNOTS - 2) {{
        idx = SOC_OBS_N_KNOTS - 2;
    }}
    float frac = x - (float)idx;
    return SOC_OBS_KNOTS[idx] + (SOC_OBS_KNOTS[idx + 1] - SOC_OBS_KNOTS[idx]) * frac;
}}

float soc_obs_ocv_inv(float v)
{{
    float lo = 0.0f;
    float hi = 1.0f;
    for (int it = 0; it < 30; it++) {{
        float mid = 0.5f * (lo + hi);
        if (soc_obs_ocv(mid) < v) {{
            lo = mid;
        }} else {{
            hi = mid;
        }}
    }}
    return 0.5f * (lo + hi);
}}

void soc_obs_init(soc_obs_t *o, float v0, float soc_override)
{{
    o->soc = (soc_override >= 0.0f) ? soc_override : soc_obs_ocv_inv(v0);
    o->v1 = 0.0f;
    o->rest_ms = 0u;
    o->a = expf(-DT_S / TAU_S);
}}

float soc_obs_step(soc_obs_t *o, float i_meas, float v_meas)
{{
    float i_d = {sgn(e['s_id'])[:-1]}f) * i_meas;
    o->v1 = o->a * o->v1 + R1_OHM * (1.0f - o->a) * i_d;
    o->soc = o->soc + {sgn(e['s_cc'])[:-1]}f) * i_d * DT_INT_S / (3600.0f * Q_AH);
    if (fabsf(i_meas) < REST_I_A) {{
        o->rest_ms = o->rest_ms + DT_MS;
    }} else {{
        o->rest_ms = 0u;
    }}
    float gain = (o->rest_ms >= REST_MS) ? L_REST : L_GAIN;
    float vm = soc_obs_ocv(o->soc) + {sgn(e['s_r0'])[:-1]}f) * R0_OHM * i_d + {sgn(e['s_v1'])[:-1]}f) * o->v1;
    o->soc = o->soc + {sgn(e['s_corr'])[:-1]}f) * gain * (v_meas - vm);
{sat}    return o->soc;
}}
"""


def expect_header(spec):
    """Unit-test expectations computed from the spec with the float64 reference (design intent)."""
    k = spec["params"]["knots"]
    pts = [i / 20.0 for i in range(-1, 22)]  # includes s<0 and s>1 (extrapolation by end segments)
    ocv_vals = [ref.ocv(s, k) for s in pts]
    inv_pts = [0.05 * i for i in range(1, 20)]
    return ("/* Generated by gen.py: unit-test expectations from the spec. Do not edit. */\n"
            f"#define UT_N_OCV {len(pts)}\n"
            f"static const double UT_OCV_S[UT_N_OCV] = {{{', '.join(repr(s) for s in pts)}}};\n"
            f"static const double UT_OCV_V[UT_N_OCV] = {{{', '.join(repr(v) for v in ocv_vals)}}};\n"
            f"#define UT_N_INV {len(inv_pts)}\n"
            f"static const double UT_INV_S[UT_N_INV] = {{{', '.join(repr(s) for s in inv_pts)}}};\n"
            f"#define UT_SAT {1 if spec['eq']['sat'] else 0}\n")


def generate(spec, out):
    out = pathlib.Path(out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "SocObs.mo").write_text(modelica(spec))
    (out / "soc_obs.h").write_text(HEADER.format(n=len(spec["params"]["knots"])))
    (out / "soc_obs.c").write_text(c_source(spec))
    (out / "soc_obs_expect.h").write_text(expect_header(spec))
    (out / "spec.json").write_text(json.dumps(spec, indent=1))


if __name__ == "__main__":
    generate(json.loads(pathlib.Path(sys.argv[1]).read_text()), sys.argv[2])
